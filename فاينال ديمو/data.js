/* Lightweight, deterministic SEO checklist — no external calls, just
   heuristics against the title/body/focus keyword the editor is holding,
   mirroring the kind of checks newsroom CMSs surface (title length,
   keyword placement, content length, keyword density) without claiming
   to be a real SEO engine. */
function computeSeoChecklist({ title = "", body = "", keyword = "" }) {
  const plain = body.replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
  const wordCount = plain ? plain.split(" ").length : 0;
  const kw = keyword.trim();
  const titleLen = title.trim().length;
  const kwInTitle = kw && title.includes(kw);
  const kwInIntro = kw && plain.slice(0, 200).includes(kw);
  const kwCount = kw ? (plain.match(new RegExp(kw.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g")) || []).length : 0;

  const checks = [
    { ok: titleLen >= 40 && titleLen <= 70, warn: titleLen > 0 && titleLen < 40, text: `طول العنوان (${titleLen} حرفاً) — الأفضل بين 40 و70` },
    { ok: !!kwInTitle, warn: !kw, text: kw ? "الكلمة المفتاحية موجودة في العنوان" : "لم تُحدَّد كلمة مفتاحية بعد" },
    { ok: !!kwInIntro, warn: !kw, text: "الكلمة المفتاحية موجودة في الفقرة الأولى" },
    { ok: wordCount >= 300, warn: wordCount >= 150 && wordCount < 300, text: `طول المحتوى (${wordCount} كلمة) — يفضَّل 300 كلمة فأكثر` },
    { ok: kw && kwCount >= 2 && kwCount <= 6, warn: kw && (kwCount === 1 || kwCount > 6), text: kw ? `تكرار الكلمة المفتاحية: ${kwCount} مرة` : "بانتظار كلمة مفتاحية لحساب التكرار" },
  ];
  const score = Math.round((checks.filter(c => c.ok).length / checks.length) * 100);
  return { score, checks };
}