/**
 * Frontend "semantic" relevance scoring.
 * Returns [{a, score, reasons:[...]}] sorted by score desc, score>0 only.
 * Falls back gracefully: plain substring matches still score highest,
 * concept/city/country matches add relevance even without exact wording.
 */
function semanticSearch(query, pool){
  const q = (query||"").trim();
  pool = pool || ARTICLES;
  if(!q) return pool.map(a=>({a,score:0,reasons:[]}));

  const matchedConcepts = SEMANTIC_CONCEPTS.filter(c=> c.keywords.some(k=> q.includes(k)) );
  const matchedCountries = COUNTRIES.filter(c=> q.includes(c.name)).map(c=>c.name);
  const allCities = [...new Set(ARTICLES.map(a=>a.city).filter(Boolean))];
  const matchedCities = allCities.filter(city=> q.includes(city));

  const out = pool.map(a=>{
    let score = 0; const reasons = [];
    if(a.title.includes(q)) score += 6;
    if(a.excerpt && a.excerpt.includes(q)) score += 2;
    if(a.city && matchedCities.includes(a.city)){ score += 4; reasons.push(`مرتبط بمدينة ${a.city}`); }
    if(a.country && matchedCountries.includes(a.country)){ score += 4; reasons.push(`مرتبط بدولة ${a.country}`); }
    matchedConcepts.forEach(c=>{ if(a.cat === c.cat){ score += 3; reasons.push(`مرتبط بـ ${c.label}`); } });
    if(a.cat && q.includes(a.cat)) score += 3;
    return {a, score, reasons:[...new Set(reasons)]};
  }).filter(r=>r.score>0);

  out.sort((x,y)=>y.score-x.score);
  return out;
}

function searchIntentSummary(query){
  const q=(query||"").trim(); if(!q) return null;
  const concepts = SEMANTIC_CONCEPTS.filter(c=> c.keywords.some(k=> q.includes(k))).map(c=>c.label);
  const countries = COUNTRIES.filter(c=> q.includes(c.name)).map(c=>c.name);
  const allCities = [...new Set(ARTICLES.map(a=>a.city).filter(Boolean))];
  const cities = allCities.filter(city=> q.includes(city));
  const bits = [...new Set([...cities, ...countries, ...concepts])];
  return bits.length ? bits : null;
}

